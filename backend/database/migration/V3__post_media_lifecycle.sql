-- =========================================================
-- V3__post_media_lifecycle.sql
-- LC-S2-01:
-- - Soft delete cho posts (deleted_at)
-- - Presigned upload session (media_uploads) + media cleanup queue
-- - Unique constraint chống duplicate friend request pending (LC-S1-03)
-- =========================================================

ALTER TABLE posts ADD COLUMN deleted_at TIMESTAMPTZ;

CREATE TABLE media_uploads (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  object_key TEXT NOT NULL UNIQUE,

  status VARCHAR(20) NOT NULL DEFAULT 'UPLOADING',
  media_type VARCHAR(16),

  expires_at TIMESTAMPTZ NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  finalized_at TIMESTAMPTZ,

  CONSTRAINT chk_media_uploads_status
    CHECK (status IN ('UPLOADING', 'FINALIZED', 'EXPIRED'))
);

CREATE TABLE media_cleanup_queue (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  object_key TEXT NOT NULL UNIQUE,

  scheduled_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  attempts INT NOT NULL DEFAULT 0,
  last_error TEXT,
  done_at TIMESTAMPTZ
);

CREATE INDEX idx_media_uploads_active
  ON media_uploads (status, expires_at);

CREATE INDEX idx_media_cleanup_pending
  ON media_cleanup_queue (scheduled_at)
  WHERE done_at IS NULL;

-- Chống duplicate friend request đang PENDING (giả lập song song)
CREATE UNIQUE INDEX uq_friend_requests_pending
  ON friend_requests (sender_id, receiver_id)
  WHERE status = 'PENDING';

GRANT SELECT, INSERT, UPDATE, DELETE
  ON media_uploads, media_cleanup_queue
  TO post_service_user;