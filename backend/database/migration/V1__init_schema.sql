CREATE TABLE account_deletion_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  status deletion_status NOT NULL DEFAULT 'PENDING',

  requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  scheduled_purge_at TIMESTAMPTZ,
  purged_at TIMESTAMPTZ,
  cancelled_at TIMESTAMPTZ
);

-- =========================================================
-- 3. FRIEND / BLOCK
-- =========================================================

CREATE TABLE friend_requests (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  receiver_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  status request_status NOT NULL DEFAULT 'PENDING',

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ,

  CONSTRAINT chk_friend_requests_not_self CHECK (sender_id <> receiver_id)
);

CREATE TABLE friendships (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  user_id_a BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  user_id_b BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT chk_friendships_order CHECK (user_id_a < user_id_b),
  CONSTRAINT uq_friendships_pair UNIQUE (user_id_a, user_id_b)
);

CREATE TABLE blocks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  blocker_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  blocked_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT chk_blocks_not_self CHECK (blocker_id <> blocked_id),
  CONSTRAINT uq_blocks_pair UNIQUE (blocker_id, blocked_id)
);

-- Chống A gửi B và B gửi A cùng lúc khi request đang PENDING.
CREATE UNIQUE INDEX uq_friend_requests_pending_pair
ON friend_requests (LEAST(sender_id, receiver_id), GREATEST(sender_id, receiver_id))
WHERE status = 'PENDING';

-- =========================================================
-- 4. POST / MEDIA / AI
-- =========================================================

CREATE TABLE ai_generations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  original_media_url TEXT,
  style_prompt TEXT,
  generated_media_url TEXT,

  generation_type generation_type NOT NULL,
  status generation_status NOT NULL DEFAULT 'PENDING',

  error_message TEXT,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ,
  completed_at TIMESTAMPTZ
);

CREATE TABLE posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  media_type media_type NOT NULL,
  media_url TEXT NOT NULL,
  thumbnail_url TEXT,

  media_width INT,
  media_height INT,
  file_size_bytes BIGINT,
  duration_seconds INT,

  caption TEXT,
  filter_applied VARCHAR(100),

  is_ai_generated BOOLEAN NOT NULL DEFAULT false,
  ai_generation_id BIGINT REFERENCES ai_generations(id) ON DELETE SET NULL,

  visibility post_visibility NOT NULL DEFAULT 'FRIENDS_ONLY',
  status post_status NOT NULL DEFAULT 'ACTIVE',

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ,

  CONSTRAINT chk_posts_gif_duration CHECK (
    media_type <> 'GIF'
    OR duration_seconds IS NULL
    OR (duration_seconds >= 0 AND duration_seconds <= 5)
  ),
  CONSTRAINT chk_posts_media_size CHECK (
    file_size_bytes IS NULL OR file_size_bytes >= 0
  ),
  CONSTRAINT chk_posts_media_dimensions CHECK (
    (media_width IS NULL OR media_width > 0)
    AND
    (media_height IS NULL OR media_height > 0)
  )
);

-- Vì DBML dùng ref: - cho ai_generation_id, ta đảm bảo 1 AI generation chỉ gắn với tối đa 1 post.
CREATE UNIQUE INDEX uq_posts_ai_generation_id
ON posts(ai_generation_id)
WHERE ai_generation_id IS NOT NULL;

CREATE TABLE saved_posts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  post_id BIGINT NOT NULL REFERENCES posts(id) ON DELETE CASCADE,

  saved_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT uq_saved_posts_user_post UNIQUE (user_id, post_id)
);

-- =========================================================
-- 5. CHAT
-- =========================================================

CREATE TABLE conversations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  user_id_1 BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  user_id_2 BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  last_message_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT chk_conversations_order CHECK (user_id_1 < user_id_2),
  CONSTRAINT uq_conversations_pair UNIQUE (user_id_1, user_id_2)
);

CREATE TABLE messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  conversation_id BIGINT NOT NULL REFERENCES conversations(id) ON DELETE CASCADE,
  sender_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  content TEXT,
  media_url TEXT,
  thumbnail_url TEXT,

  message_type message_type NOT NULL DEFAULT 'TEXT',
  status message_status NOT NULL DEFAULT 'SENT',

  sent_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  delivered_at TIMESTAMPTZ,
  read_at TIMESTAMPTZ,

  CONSTRAINT chk_messages_payload CHECK (
    (message_type IN ('TEXT', 'SYSTEM') AND content IS NOT NULL)
    OR
    (message_type IN ('IMAGE', 'GIF') AND media_url IS NOT NULL)
  )
);

-- =========================================================
-- 6. ADMIN / MODERATION / NOTIFICATION
-- =========================================================

CREATE TABLE admins (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  username VARCHAR(50) UNIQUE NOT NULL,
  password_hash TEXT NOT NULL,

  role admin_role NOT NULL DEFAULT 'MODERATOR',

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ
);

CREATE TABLE notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  actor_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,

  type notification_type NOT NULL,

  reference_id BIGINT,
  title VARCHAR(255),
  body TEXT,

  is_read BOOLEAN NOT NULL DEFAULT false,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  read_at TIMESTAMPTZ
);

CREATE TABLE device_tokens (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  fcm_token TEXT UNIQUE NOT NULL,
  platform platform_type NOT NULL,

  is_active BOOLEAN NOT NULL DEFAULT true,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ,
  last_used_at TIMESTAMPTZ
);

CREATE TABLE reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  reporter_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,

  reported_post_id BIGINT REFERENCES posts(id) ON DELETE SET NULL,
  reported_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,

  reason TEXT NOT NULL,

  status report_status NOT NULL DEFAULT 'PENDING',
  action_taken report_action NOT NULL DEFAULT 'NONE',

  handled_by_admin_id BIGINT REFERENCES admins(id) ON DELETE SET NULL,
  resolution_note TEXT,

  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  resolved_at TIMESTAMPTZ,

  CONSTRAINT chk_reports_only_one_target CHECK (
    (reported_post_id IS NOT NULL AND reported_user_id IS NULL)
    OR
    (reported_post_id IS NULL AND reported_user_id IS NOT NULL)
  )
);

