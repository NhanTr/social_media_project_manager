-- =========================================================
-- 2. USERS / AUTH / TERMS / ACCOUNT DELETION
-- =========================================================

CREATE TABLE users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  username VARCHAR(50) UNIQUE NOT NULL,
  email VARCHAR(255) UNIQUE,
  phone_number VARCHAR(30) UNIQUE,

  auth_provider auth_provider NOT NULL,
  google_id VARCHAR(255) UNIQUE,

  display_name VARCHAR(100),
  avatar_url TEXT,
  bio TEXT,

  status user_status NOT NULL DEFAULT 'ACTIVE',
  friend_invite_code VARCHAR(100) UNIQUE,

  last_login_at TIMESTAMPTZ,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  updated_at TIMESTAMPTZ,
  deleted_at TIMESTAMPTZ,

  CONSTRAINT chk_users_auth_provider_identity CHECK (
    (auth_provider = 'GOOGLE' AND google_id IS NOT NULL)
    OR
    (auth_provider = 'PHONE' AND phone_number IS NOT NULL)
  )
);

CREATE TABLE terms_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  version VARCHAR(50) UNIQUE NOT NULL,
  content_url TEXT NOT NULL,
  is_active BOOLEAN NOT NULL DEFAULT true,

  published_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE user_terms_acceptance (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  terms_version_id BIGINT NOT NULL REFERENCES terms_versions(id) ON DELETE RESTRICT,

  accepted_at TIMESTAMPTZ NOT NULL DEFAULT now(),

  CONSTRAINT uq_user_terms_acceptance UNIQUE (user_id, terms_version_id)
);

INSERT INTO terms_versions (version, content_url, is_active)
