-- Duplicate submissions are rejected even when requests arrive concurrently.
-- Existing duplicate submissions are retained for audit and migration fails rather than silently deleting them.
CREATE UNIQUE INDEX uq_reports_reporter_post ON reports(reporter_id, reported_post_id) WHERE reported_post_id IS NOT NULL;
CREATE UNIQUE INDEX uq_reports_reporter_user ON reports(reporter_id, reported_user_id) WHERE reported_user_id IS NOT NULL;
CREATE INDEX idx_reports_queue ON reports(status, id DESC);
ALTER TABLE reports ADD COLUMN notification_delivered BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE reports ADD COLUMN next_attempt_at TIMESTAMPTZ;
ALTER TABLE reports ADD COLUMN attempt_count INTEGER NOT NULL DEFAULT 0;
CREATE INDEX idx_reports_recovery ON reports(next_attempt_at, id) WHERE status = 'INVESTIGATING' OR notification_delivered = false;

CREATE TABLE moderation_audit (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT NOT NULL REFERENCES reports(id) ON DELETE RESTRICT,
  admin_id BIGINT NOT NULL,
  action VARCHAR(40) NOT NULL,
  outcome VARCHAR(40) NOT NULL CHECK (outcome IN ('REQUESTED','APPLIED','DOWNSTREAM_UNCONFIRMED','RESULT_NOTIFIED')),
  note TEXT NOT NULL CHECK (length(trim(note)) > 0),
  occurred_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_moderation_audit_report ON moderation_audit(report_id, id);
-- Runtime principal cannot change or delete an existing audit row, even with direct SQL.
GRANT SELECT, INSERT ON moderation_audit TO moderation_service_user;
GRANT USAGE, SELECT ON SEQUENCE moderation_audit_id_seq TO moderation_service_user;
CREATE FUNCTION immutable_moderation_audit() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'Moderation audit records are immutable'; END;
$$;
CREATE TRIGGER immutable_moderation_audit BEFORE UPDATE OR DELETE ON moderation_audit
FOR EACH ROW EXECUTE FUNCTION immutable_moderation_audit();
