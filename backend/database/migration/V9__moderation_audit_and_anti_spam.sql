-- Migration V9: Bảng Audit Log bất biến và Ràng buộc chống spam report trùng cho Moderation Service

CREATE TABLE moderation_audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  report_id BIGINT REFERENCES reports(id) ON DELETE SET NULL,
  admin_id BIGINT NOT NULL REFERENCES admins(id) ON DELETE CASCADE,
  target_type VARCHAR(20) NOT NULL,
  target_id BIGINT NOT NULL,
  action_taken report_action NOT NULL,
  reason_note TEXT,
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT chk_moderation_audit_target_type CHECK (
    target_type IN ('POST', 'USER')
  )
);

-- Ràng buộc chống spam report trùng: 1 user chỉ có tối đa 1 report ở trạng thái PENDING cho cùng 1 mục tiêu
CREATE UNIQUE INDEX uq_reports_pending_post
  ON reports(reporter_id, reported_post_id)
  WHERE status = 'PENDING' AND reported_post_id IS NOT NULL;

CREATE UNIQUE INDEX uq_reports_pending_user
  ON reports(reporter_id, reported_user_id)
  WHERE status = 'PENDING' AND reported_user_id IS NOT NULL;

-- Phân quyền cho moderation_service_user (chỉ SELECT và INSERT để đảm bảo tính bất biến của Audit Log)
GRANT SELECT, INSERT
ON moderation_audit_logs
TO moderation_service_user;

GRANT USAGE, SELECT
ON SEQUENCE moderation_audit_logs_id_seq
TO moderation_service_user;
